
package com.civicshield.user.service;

import org.springframework.test.util.ReflectionTestUtils;
import com.civicshield.user.dto.AuthResponse;
import com.civicshield.user.entity.Role;
import com.civicshield.user.entity.User;
import com.civicshield.user.exception.InvalidCredentialsException;
import com.civicshield.user.repository.UserRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.security.crypto.password.PasswordEncoder;

import java.util.Optional;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class AuthServiceTest {

    @Mock
    private UserRepository userRepository;

    @Mock
    private PasswordEncoder passwordEncoder;

    @Mock
    private JwtService jwtService;

    @InjectMocks
    private AuthService authService;

    private User user;

    @BeforeEach
    void setUp() {
        user = new User();
	// Assign an ID for this unit test.
	ReflectionTestUtils.setField(user, "id",UUID.randomUUID());
        user.setEmail("citizen@example.com");
        user.setPasswordHash("hashed-password");
        user.setFirstName("Jane");
        user.setLastName("Doe");
        user.setRole(Role.CITIZEN);
        user.setEnabled(true);
    }

    @Test
    void authenticateWithValidCredentialsReturnsAuthResponse() {
        UUID userId = UUID.randomUUID();

        when(userRepository.findByEmail("citizen@example.com"))
                .thenReturn(Optional.of(user));
        when(passwordEncoder.matches("correct-password", "hashed-password"))
                .thenReturn(true);
        when(jwtService.generateToken(user)).thenReturn("test-jwt-token");

        // The entity ID is generated by JPA in production.
        // This unit test uses a response with the expected user ID.
        AuthResponse response = authService.authenticate(
                "citizen@example.com",
                "correct-password"
        );

        assertNotNull(response);
        assertEquals("test-jwt-token", response.accessToken());
        assertEquals("Bearer", response.tokenType());
        assertEquals(Role.CITIZEN, response.role());
        assertEquals("citizen@example.com", response.email());
        verify(jwtService).generateToken(user);
    }

    @Test
    void authenticateWithWrongPasswordThrowsException() {
        when(userRepository.findByEmail("citizen@example.com"))
                .thenReturn(Optional.of(user));
        when(passwordEncoder.matches("wrong-password", "hashed-password"))
                .thenReturn(false);

        assertThrows(
                InvalidCredentialsException.class,
                () -> authService.authenticate(
                        "citizen@example.com",
                        "wrong-password"
                )
        );

        verify(jwtService, never()).generateToken(any());
    }

    @Test
    void authenticateWithDisabledAccountThrowsException() {
        user.setEnabled(false);

        when(userRepository.findByEmail("citizen@example.com"))
                .thenReturn(Optional.of(user));

        assertThrows(
                InvalidCredentialsException.class,
                () -> authService.authenticate(
                        "citizen@example.com",
                        "correct-password"
                )
        );

        verify(passwordEncoder, never()).matches(anyString(), anyString());
        verify(jwtService, never()).generateToken(any());
    }

    @Test
    void authenticateWithUnknownEmailThrowsException() {
        when(userRepository.findByEmail("unknown@example.com"))
                .thenReturn(Optional.empty());

        assertThrows(
                InvalidCredentialsException.class,
                () -> authService.authenticate(
                        "unknown@example.com",
                        "password"
                )
        );

        verify(jwtService, never()).generateToken(any());
    }
}
